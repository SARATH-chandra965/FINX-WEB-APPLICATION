export function translateSignal(
  language: Language,
  signal: { id: string; title: string; explanation: string },
): { title: string; explanation: string } {
  const localized = additionalSignalTranslations[language]?.[signal.id];
  if (localized) return { title: localized[0], explanation: localized[1] };
  const text = signalTranslations[signal.id];
  if (!text) return signal;
  return language === "te"
    ? { title: text[1], explanation: text[3] }
    : { title: text[0], explanation: text[2] };
}

export function translateRiskSummary(language: Language, level: "low" | "medium" | "high"): string {
  const key: Record<typeof level, TranslationKey> = {
    low: "summaryLow",
    medium: "summaryMedium",
    high: "summaryHigh",
  };
  return translate(language, key[level]);
}

export function translateRecommendations(language: Language, level: "low" | "medium" | "high"): string[] {
  const keys: Record<typeof level, [TranslationKey, TranslationKey]> = {
    low: ["recommendationLow1", "recommendationLow2"],
    medium: ["recommendationMedium1", "recommendationMedium2"],
    high: ["recommendationHigh1", "recommendationHigh2"],
  };
  return keys[level].map((key) => translate(language, key));
}